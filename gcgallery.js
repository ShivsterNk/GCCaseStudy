document.addEventListener("DOMContentLoaded", () => {

    const imagesPerPage = 12;
    let currentPage = 1;
    let filteredImages = allImages;

	const resultsCount = document.getElementById("resultsCount");
	console.log("resultsCount:", resultsCount);

    const galleryContainer = document.getElementById('imageGallery');
    const pageNumberDisplay = document.getElementById('pageNumber');
    const firstButton = document.getElementById('firstButton');
    const prevButton = document.getElementById('prevButton');
    const nextButton = document.getElementById('nextButton');
    const lastButton = document.getElementById('lastButton');

    const modal = document.getElementById('imageModal');
    const modalImage = document.getElementById('modalImage');
    const modalClose = document.getElementById('modalClose');

    const searchBox = document.getElementById("searchBox");

    function renderGallery() {
        galleryContainer.innerHTML = '';

        const totalPages = Math.ceil(filteredImages.length / imagesPerPage);
        const start = (currentPage - 1) * imagesPerPage;
        const imagesToDisplay = filteredImages.slice(start, start + imagesPerPage);

		if (resultsCount) {
			if (filteredImages.length === 0) {
				resultsCount.textContent = "No photos found";
			} else {
				const end = Math.min(start + imagesPerPage, filteredImages.length);

				resultsCount.textContent =
					`Showing ${start + 1}-${end} of ${filteredImages.length} photos`;
			}
		}

        imagesToDisplay.forEach((image, index) => {
                const imgElement = document.createElement('img');
                imgElement.src = image.src;
                imgElement.classList.add('gallery-image', 'fade-in');
                imgElement.loading = "lazy";

                const descElement = document.createElement('p');
                descElement.textContent = image.desc;
                descElement.classList.add('image-description');

                const container = document.createElement('div');
                container.classList.add('image-container');

                imgElement.addEventListener('click', () => openModal(image.src));

                container.appendChild(imgElement);
                container.appendChild(descElement);

                galleryContainer.appendChild(container);
        });

        pageNumberDisplay.textContent = `Page ${currentPage}`;

        firstButton.disabled = currentPage === 1;
        prevButton.disabled = currentPage === 1;
        nextButton.disabled = currentPage === totalPages;
        lastButton.disabled = currentPage === totalPages;
    }

    function openModal(src) {
        modal.style.display = 'flex';
        modalImage.src = src;
    }

    modalClose.addEventListener('click', () => {
        modal.style.display = 'none';
    });

    modal.addEventListener('click', (e) => {
        if (e.target === modal) modal.style.display = 'none';
    });

    window.navigatePage = function (direction) {
        const totalPages = Math.ceil(filteredImages.length / imagesPerPage);

        if (direction === 'next' && currentPage < totalPages) currentPage++;
        else if (direction === 'prev' && currentPage > 1) currentPage--;
        else if (direction === 'first') currentPage = 1;
        else if (direction === 'last') currentPage = totalPages;

        renderGallery();
    };

    // SEARCH (safe check added)
    if (searchBox) {
        searchBox.addEventListener("input", () => {
            const query = searchBox.value.toLowerCase().trim();

            filteredImages = allImages.filter(img =>
                img.desc.toLowerCase().includes(query)
            );

            currentPage = 1;
            renderGallery();
        });
    }

    // FILTERS
    document.querySelectorAll("#filters button").forEach(btn => {
        btn.addEventListener("click", () => {

			document.querySelectorAll("#filters button").
				forEach(b => b.classList.remove("active"));

			btn.classList.add("active");

            const cat = btn.dataset.cat;

            filteredImages = (cat === "all")
                ? allImages
                : allImages.filter(img => img.category === cat);

            currentPage = 1;
            renderGallery();
        });
    });

	

    renderGallery();
});
